function renderCorpus() {
  const box = document.getElementById("corpusBody");
  if (!box) return;
  const cnt = document.getElementById("corpusCount");
  if (cnt) {
    let text = "";
    try { text = TAB_COUNT[corpusTab] ? TAB_COUNT[corpusTab]() : ""; } catch (e) {}
    cnt.textContent = text;
  }
  box.innerHTML = corpusHTML();
}

function initCorpus() {
  const tabs = document.getElementById("corpusTabs");
  if (!tabs) return;
  tabs.addEventListener("click", function (e) {
    const btn = e.target.closest("[data-ctab]");
    if (!btn) return;
    corpusTab = btn.getAttribute("data-ctab");
    tabs.querySelectorAll("[data-ctab]").forEach(function (p) {
      const on = p === btn;
      p.classList.toggle("is-active", on);
      p.setAttribute("aria-selected", String(on));   // 화면낭독기에 선택 상태 전달
    });
    if (typeof Voice !== "undefined" && Voice.stop) Voice.stop();
    if (corpusTab === "lessons") { openLessons(); return; }
    renderCorpus();
  });

  const body = document.getElementById("corpusBody");
  body.addEventListener("click", function (e) {
    if (typeof handleLessonClick === "function" && handleLessonClick(e)) return;
    const h = e.target.closest("[data-hwadu]");
    if (h) { useHwadu(h.getAttribute("data-hwadu")); return; }
    const c = e.target.closest("[data-course]");
    if (c) { useCourse(parseInt(c.getAttribute("data-course"), 10)); return; }
    const sc = e.target.closest("[data-scenario]");
    if (sc) { useScenario(parseInt(sc.getAttribute("data-scenario"), 10)); return; }
    const my = e.target.closest("[data-myth]");
    if (my) { useMyth(my.getAttribute("data-myth")); }
  });

  renderCorpus();
}

/* 화두 → 수업 설계 폼으로 */
function useHwadu(name) {
  const all = hwaduFlat();
  const h = all.filter(function (x) { return x.name === name; })[0];
  if (!h) return;
  const title = document.getElementById("f-title");
  const note = document.getElementById("f-note");
  if (title && !title.value) title.value = h.name;
  if (note) {
    note.value = (note.value ? note.value + "\n" : "") +
      "화두: " + h.name + " / 던질 질문: " + h.question + " / 관찰 지점: " + h.spot;
  }
  navigate("design");
  if (typeof toast === "function") toast("화두 「" + h.name + "」을(를) 수업 설계에 담았습니다");
}

/* 코스 → 수업 설계 폼으로 */
function useCourse(no) {
  const c = COURSES.filter(function (x) { return x.no === no; })[0];
  if (!c) return;
  const note = document.getElementById("f-note");
  const title = document.getElementById("f-title");
  const place = document.getElementById("f-place");
  if (title && !title.value) title.value = c.title;
  if (place && !place.value) place.value = c.trees[0] || c.area;
  if (note) {
    note.value = (note.value ? note.value + "\n" : "") +
      c.no + "코스 「" + c.title + "」 / 동선: " + c.route +
      " / 주요 노거수: " + c.trees.join(", ") + " / 화두: " + c.hwadu +
      " / 해설 포인트: " + c.point;
  }
  navigate("design");
  if (typeof toast === "function") toast(c.no + "코스를 수업 설계에 담았습니다");
}

