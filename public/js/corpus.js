function useMyth(name) {
  const m = MYTHS.filter(function (x) { return x.n === name; })[0];
  if (!m) return;
  const title = document.getElementById("f-title");
  const note = document.getElementById("f-note");
  const topic = document.getElementById("f-topic");
  if (title && !title.value) title.value = m.n + "와(과) " + m.who;
  if (topic && !topic.value) topic.value = m.n;
  if (note) {
    note.value = (note.value ? note.value + "\n" : "") +
      "그리스 신화 연결: " + m.n + "(" + m.s + ") / " + m.who + " — " + m.story +
      " / 현장 관찰: " + m.here +
      (m.fix ? " / 반드시 지킬 것: " + m.fix : "");
  }
  navigate("design");
  if (typeof toast === "function") toast("「" + m.n + "」 신화를 수업 설계에 담았습니다");
}
