function useScenario(day) {
  const s = SCENARIOS.filter(function (x) { return x.day === day; })[0];
  if (!s) return;
  const title = document.getElementById("f-title");
  const note = document.getElementById("f-note");
  if (title && !title.value) title.value = s.title;
  if (note) {
    note.value = (note.value ? note.value + "\n" : "") +
      s.key + " 편 「" + s.title + "」 / 단계: " +
      s.periods.map(function (p) { return p[1]; }).join(" → ");
  }
  navigate("design");
  if (typeof toast === "function") toast(s.key + " 편을 수업 설계에 담았습니다");
}

