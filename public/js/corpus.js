            '<p style="margin:.4rem 0">' + esc(m.story) + '</p>' +
            '<p class="quote" style="margin:.4rem 0">' + esc(m.read) + '</p>' +
            (m.fix ? '<p class="caution-box">✎ ' + esc(m.fix) + '</p>' : '') +
            '<button class="btn btn-sm" type="button" data-myth="' + esc(m.n) + '">이 이야기로 수업 설계</button>' +
            '</div>';
